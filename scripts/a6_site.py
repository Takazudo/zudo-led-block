#!/usr/bin/env python3
"""Deterministic A6 -> documentation bridge (standard library only).

  generate [--check]   Write doc/src/content/docs/project/a6.mdx from the A6 revision files.
                       With --check, write nothing and fail if the page is missing or stale.

Inputs (read only): engineering/a6/manifest.json, engineering/a6/electronics/
placement_and_connectivity.json, engineering/a6/electronics/routing_constraints.json,
engineering/a6/verification/{native_expectations,native_reproduction,mechanical_impact,
layout_rationale}.json and engineering/a5/electronics/placement_and_connectivity.json.
The page separates A5 history, the current A6 state, the fresh CI check and what
remains to qualify. It never claims a manufacturing release.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
A6 = ROOT / "engineering" / "a6"
A5 = ROOT / "engineering" / "a5"
PAGE = ROOT / "doc" / "src" / "content" / "docs" / "project" / "a6.mdx"
GITHUB = "https://github.com/Takazudo/zudo-led-block/blob/main/"
DESIGN_JA = {"controller": "制御基板 (A6 配線済み候補)", "led_leaf": "LED 基板 (A5 のまま)", "power_adapter": "電源変換基板 (A5 のまま)"}


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def esc(value) -> str:
    if value is None:
        return "—"
    text = str(value)
    for old, new in (("\\", "\\\\"), ("|", "\\|"), ("{", "\\{"), ("}", "\\}"), ("<", "&lt;"), (">", "&gt;"),
                     ("\n", " "), ("*", "\\*"), ("_", "\\_")):
        text = text.replace(old, new)
    return text


def table(headers, rows, align=None) -> str:
    align = align or ["---"] * len(headers)
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(align) + " |"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def link(rel: str, label: str | None = None) -> str:
    return f"[`{label or rel}`]({GITHUB}{rel})"


def placement_rows():
    a5 = {c["ref"]: c for c in load(A5 / "electronics/placement_and_connectivity.json")["boards"][0]["components"]}
    a6 = {c["ref"]: c for c in load(A6 / "electronics/placement_and_connectivity.json")["boards"][0]["components"]}
    reasons = load(A6 / "verification/layout_rationale.json")["parts"]
    rows, unchanged = [], []
    for ref in sorted(a5, key=lambda r: (r.rstrip("0123456789"), int(r[len(r.rstrip("0123456789")):] or 0))):
        p, q = a5[ref], a6[ref]
        before = (round(p["at"][0], 3), round(p["at"][1], 3), p["side"], round(p["angle"] % 360, 1))
        after = (round(q["at"][0], 3), round(q["at"][1], 3), q["side"], round(q["angle"] % 360, 1))
        if before == after:
            unchanged.append(ref)
            continue
        if ref not in reasons:
            raise SystemExit(f"moved part {ref} has no reason in layout_rationale.json")
        fmt = lambda t: f"{t[0]:g}, {t[1]:g} / {t[2]} / {t[3]:g}°"
        rows.append([f"`{ref}`", esc(p["value"]), fmt(before), fmt(after), esc(reasons[ref])])
    extra = set(reasons) - {r[0].strip("`") for r in rows}
    if extra:
        raise SystemExit(f"layout_rationale.json lists parts that did not move: {sorted(extra)}")
    return rows, unchanged


def page() -> str:
    manifest = load(A6 / "manifest.json")
    expect = load(A6 / "verification/native_expectations.json")
    rec = load(A6 / "verification/native_reproduction.json")
    mech = load(A6 / "verification/mechanical_impact.json")
    rc = load(A6 / "electronics/routing_constraints.json")
    export = load(A6 / "electronics/placement_and_connectivity.json")
    board_sha = next(f["sha256"] for f in manifest["files"] if f["path"] == manifest["authoritative_board"])
    if rec["tested_board_sha256"] != board_sha:
        raise SystemExit("native_reproduction.json was recorded on a different board than the manifest names")
    if export["controller_board_sha256"] != board_sha:
        raise SystemExit("placement export is stale for the current board")
    if mech["placement_export_sha256"] != next(f["sha256"] for f in manifest["files"]
                                               if f["path"] == "engineering/a6/electronics/placement_and_connectivity.json"):
        raise SystemExit("mechanical_impact.json was recorded on a different placement export")
    ctrl = next(b for b in export["boards"] if b["name"] == "controller")
    out = ["---", 'title: "A6 制御基板 (配線済み候補)"',
           'description: "A6 の制御基板レイアウト、ネイティブ検証、機構への影響。engineering/a6/ から自動生成。"',
           "sidebar_position: 3", "---", "",
           "{/* GENERATED by scripts/a6_site.py from engineering/a6/ — do not edit; run `python3 scripts/a6_site.py generate` */}", ""]
    out.append(":::danger[製造リリースではありません]\n"
               "A6 は制御基板の配置と 4 層配線だけを加えた **設計候補** です。試作・実機評価・製造業者の確認は行っていません。"
               "ネイティブ検証が通っても電子回路や製造の承認にはなりません。\n:::\n")
    out.append("## 4 つの区別\n")
    out.append(table(["区分", "内容"], [
        ["A5 の履歴", "A5 の制御基板は配置のみ・未配線 (未接続 130、コートヤード重なり J3-H1 / J3-C7)。[A5 の現状](/docs/project/status/) と [履歴上の検証記録](/docs/verification/historical-records/) にそのまま残しています。"],
        ["A6 の現状", f"制御基板を 4 層で配線 (配線 {ctrl['track_count']} 本、ビア {ctrl['via_count']} 個)。回路 (ネットリスト) と固定インターフェースは A5 のまま。"],
        ["新たな検証", "CI の `a6-native` ジョブが PR と main への push ごとに KiCad 10.0.8 (ダイジェスト固定) で 3 種類の設計すべてを再検証します。"],
        ["残る評価", "実機の電気・温度・信号品質、ハーネスの装着適合、製造業者のスタックアップ確認、物理試作。"],
    ]))
    out.append("\n## 何が権威か\n")
    out.append(f"配置と銅箔の出典は配線済みの {link(manifest['authoritative_board'])} だけです "
               f"(SHA-256 `{board_sha[:16]}…`)。通常の生成 (`scripts/a6_controller.py generate`) はこのファイルを書かず、"
               "CI は生成の前後でハッシュが変わらないことを確認します。初期 (未配線) 基板の再生成はリポジトリ外の空ディレクトリにだけ行えます。"
               f"継承した A5 入力 {sum(1 for f in manifest['files'] if f['ownership'] == 'inherited_a5')} ファイルは {link('engineering/a6/manifest.json')} にパスと SHA-256 で固定しています。\n")
    out.append("## ネイティブ検証 (記録)\n")
    out.append(f"{esc(rec['recorded_utc'])} UTC にリポジトリ外で実行した記録です (KiCad {esc(rec['kicad_version'])}、"
               f"`{esc(rec['image'].split('@')[0])}` ダイジェスト固定)。同じ確認を CI が毎回新たに実行します。\n")
    rows = []
    for name, r in rec["designs"].items():
        rows.append([esc(DESIGN_JA.get(name, name)), str(r["erc_violations"]), str(r["drc_violations"]), str(r["unconnected"]),
                     str(r["parity_items"]), str(r["independent_parity_errors"]), "PASS" if r["ok"] else "FAIL"])
    out.append(table(["設計", "ERC", "DRC 違反", "未接続", "回路との差異 (KiCad)", "独立照合の差異", "判定"], rows,
                     ["---", "---:", "---:", "---:", "---:", "---:", "---"]))
    out.append("\n許容している項目は理由とともに " + link("engineering/a6/verification/native_expectations.json") +
               " に記載しています。生レポートは編集しません。\n")
    out.append("### 残る DRC 項目\n")
    res = expect["designs"]["controller"]["drc_residuals"]
    out.append(table(["ID", "種類", "対象", "理由"], [[esc(r["id"]), esc(r["type"]), esc(" / ".join(r["refs"])), esc(r["reason"])] for r in res]))
    out.append("\nこの項目があるため、A6 の制御基板を「DRC クリーン」とは呼びません。根拠と独立レビューは "
               + link("engineering/a6/verification/residuals.md") + " にあります。\n")
    out.append("### 対照試験 (CI で毎回実行)\n")
    out.append(table(["対照", "期待する結果"], [[esc(k), esc(v)] for k, v in rec["controls_expected"].items()]))
    out.append("\n## 配置の変更\n")
    rows, unchanged = placement_rows()
    out.append(f"固定インターフェースと変更しなかった部品: {', '.join(f'`{r}`' for r in unchanged)}。\n")
    out.append(table(["部品", "値", "A5 (x, y / 面 / 角度)", "A6", "理由"], rows))
    out.append("\n## 配線の根拠\n")
    out.append(table(["項目", "出典 (SHA-256)", "適用", "状態"], [
        [esc(i["id"]), esc(i["source"].get("document", "")) + (f" (`{i['source']['sha256'][:12]}…`)" if i["source"].get("sha256") else ""),
         esc(i["applied"]), esc(i["status"])] for i in rc["items"]]))
    out.append("\n未解決: " + " ".join(f"{esc(u)}" for u in rc["unresolved"]) + "\n")
    out.append("## 機構への影響\n")
    out.append(f"CadQuery {esc(mech['cadquery'])} で A6 の配置 (配置エクスポート SHA-256 `{mech['placement_export_sha256'][:16]}…`) から "
               "2HP / 3HP の組立を一時コピー上で再生成し、A5 の配置で同じ手順を実行した基準と比べました。\n")
    rows = []
    for v, r in mech["variants"].items():
        rows.append([v.upper(), str(r["a5_retained_intersections"]), str(r["a6_retained_intersections"]),
                     esc(r["a6_new_intersections_vs_a5"] or "なし"), f"{r['a6_rear_max_mm']:g}", esc(r["service_access"])])
    out.append(table(["幅", "A5 固定部品の干渉", "A6 固定部品の干渉", "A6 で増えた干渉", "最大奥行き (mm)", "サービス性"], rows,
                     ["---", "---:", "---:", "---", "---:", "---"]))
    out.append("\n" + esc(mech["note"]) + "\n")
    out.append("## 残る評価\n")
    out.append("\n".join(f"- {esc(x)}" for x in rec["remaining"]) + "\n")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    g = sp.add_parser("generate"); g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = page()
    current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else None
    if current == text:
        print(json.dumps({"status": "PASS", "page": str(PAGE.relative_to(ROOT)), "changed": False}))
        return 0
    if a.check:
        print(f"{PAGE.relative_to(ROOT)} is stale or missing (run `python3 scripts/a6_site.py generate`)")
        return 1
    PAGE.write_text(text, encoding="utf-8")
    print(json.dumps({"status": "PASS", "page": str(PAGE.relative_to(ROOT)), "changed": True}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
