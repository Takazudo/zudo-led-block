def load(rel: str):
    return json.loads((A5 / rel).read_text(encoding="utf-8"))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def esc(value) -> str:
    """Escape a value for an MDX table cell."""
    if value is None:
        return "—"
    text = str(value)
    for old, new in (("\\", "\\\\"), ("|", "\\|"), ("{", "\\{"), ("}", "\\}"), ("<", "&lt;"), (">", "&gt;"),
                     ("\n", " "), ("*", "\\*"), ("_", "\\_")):
        text = text.replace(old, new)
    return text


def usd(value: float) -> str:
    return f"${value:,.4f}"


def table(headers, rows, align=None) -> str:
    align = align or ["---"] * len(headers)
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(align) + " |"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def frontmatter(title: str, description: str, position: int) -> str:
    return "\n".join(["---", GENERATED_HEADER, f"title: {json.dumps(title, ensure_ascii=False)}",
                      f"description: {json.dumps(description, ensure_ascii=False)}",
                      f"sidebar_position: {position}", "---", ""])


def source_link(rel: str, label: str | None = None) -> str:
    return f"[`{label or rel}`]({GITHUB_TREE}{rel})"


# ---------------------------------------------------------------- netlists
def board_designators():
    """C-code -> board -> sorted designators, from the native XML netlists."""
    result: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    unpriced: dict[str, list[str]] = defaultdict(list)
    for board in BOARDS:
        tree = ET.parse(A5 / "integration" / "native_schematic" / board / "netlist.xml")
        for comp in tree.getroot().find("components"):
            ref = comp.get("ref")
            fields = {f.get("name"): (f.text or "") for f in comp.iter("field")}
            code = fields.get("LCSC", "").strip()
            if not code:
                unpriced[board].append(ref)
                continue
            result[code][board].append(ref)
    def key(ref):
        head = "".join(ch for ch in ref if not ch.isdigit())
        tail = "".join(ch for ch in ref if ch.isdigit())
        return (head, int(tail or 0))
    for code in result:
        for board in result[code]:
            result[code][board].sort(key=key)
    for board in unpriced:
        unpriced[board].sort(key=key)
    return result, unpriced


def reconcile():
    """Return the reconciled 30-type / 81-piece facts, raising on any mismatch."""
    rows = load("procurement_rows.json")
    components = rows["components"]
    designators, unpriced = board_designators()
    per_board = Counter()
    problems = []
    for row in components:
        code = row["c_code"]
        boards = designators.get(code, {})
        fitted = sum(len(refs) * BOARD_INSTANCES[board] for board, refs in boards.items())
        if fitted != row["qty_per_module"]:
            problems.append(f"{code}: netlist fitted {fitted} != ledger qty_per_module {row['qty_per_module']}")
        for board, refs in boards.items():
            per_board[board] += len(refs)
    extra = sorted(set(designators) - {row["c_code"] for row in components})
    if extra:
        problems.append(f"netlist C-codes absent from ledger: {extra}")
    fitted_total = sum(row["qty_per_module"] for row in components)
    summary = rows["summary"]
    expected = {"types": 30, "fitted": 81, "controller": 59, "led_leaf": 10, "power_adapter": 2}
    actual = {"types": len(components), "fitted": fitted_total, **{b: per_board[b] for b in BOARDS}}
    if actual != expected:
        problems.append(f"counts {actual} != contract {expected}")
    if summary["unique_jlc_mpn_count"] != len(components) or summary["fitted_parts_per_module"] != fitted_total:
        problems.append("procurement summary disagrees with its own rows")
    unique_placements = sum(per_board.values())
    if problems:
        raise SystemExit("A5 reconciliation FAILED:\n  " + "\n  ".join(problems))
    return {"rows": rows, "designators": designators, "unpriced": unpriced, "per_board": dict(per_board),
            "fitted_total": fitted_total, "unique_placements": unique_placements}


