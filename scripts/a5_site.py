def cmd_generate(check: bool) -> int:
    stale = []
    for path, text in generated_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("Generated A5 files are stale or missing (run `pnpm a5:generate`):\n  " + "\n  ".join(stale))
        return 1
    print(json.dumps({"status": "PASS", "mode": "check" if check else "write",
                      "changed": [] if check else stale}, indent=2))
    return 0


def cmd_sync_assets() -> int:
    index = manifest_index()
    sel = selection()
    wanted = set()
    for entry in sel["files"]:
        rel = entry["path"]
        source = A5 / rel
        row = index.get(f"engineering/a5/{rel}")
        if row is None:
            raise SystemExit(f"selection entry not in seed manifest: {rel}")
        if row["bytes"] > sel["max_file_bytes"]:
            raise SystemExit(f"selection entry exceeds per-file limit: {rel}")
        if sha256(source) != row["sha256"]:
            raise SystemExit(f"source does not match seed manifest: {rel}")
        target = PUBLIC_A5 / rel
        wanted.add(target)
        if not target.exists() or sha256(target) != row["sha256"]:
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
    removed = []
    if PUBLIC_A5.exists():
        for path in sorted(PUBLIC_A5.rglob("*"), reverse=True):
            if path.is_file() and path not in wanted:
                path.unlink()
                removed.append(path.relative_to(ROOT).as_posix())
            elif path.is_dir() and not any(path.iterdir()):
                path.rmdir()
    print(json.dumps({"status": "PASS", "published_files": len(wanted), "removed_stale": removed}, indent=2))
    return 0


def cmd_check_dist(dist: Path) -> int:
    sel = selection()
    index = manifest_index()
    expected = {f"a5/{e['path']}": index[f"engineering/a5/{e['path']}"] for e in sel["files"]}
    problems = []
    files = [p for p in dist.rglob("*") if p.is_file() or p.is_symlink()]
    largest = (0, "")
    for path in files:
        rel = path.relative_to(dist).as_posix()
        if path.is_symlink():
            problems.append(f"symlink in dist: {rel}")
            continue
        size = path.stat().st_size
        largest = max(largest, (size, rel))
        if size > sel["max_file_bytes"]:
            problems.append(f"file exceeds {sel['max_file_bytes']} bytes: {rel} ({size})")
        lower = rel.lower()
        if lower.endswith(FORBIDDEN_DIST_SUFFIXES):
            problems.append(f"forbidden file type in dist: {rel}")
        if any(part in FORBIDDEN_DIST_PARTS for part in PurePosixPath(rel).parts):
            problems.append(f"forbidden path in dist: {rel}")
        if rel.startswith("a5/"):
            row = expected.get(rel)
            if row is None:
                problems.append(f"unselected A5 file in dist: {rel}")
            elif size != row["bytes"] or sha256(path) != row["sha256"]:
                problems.append(f"published A5 file differs from source: {rel}")
    missing = [rel for rel in expected if not (dist / rel).is_file()]
    problems += [f"selected A5 file missing from dist: {rel}" for rel in missing]
    if len(files) > sel["max_site_files"]:
        problems.append(f"dist has {len(files)} files (> {sel['max_site_files']})")
    if not (dist / "404.html").is_file():
        problems.append("dist/404.html missing (needed for real 404 handling)")
    report = {"status": "PASS" if not problems else "FAIL", "dist": str(dist), "files": len(files),
              "total_bytes": sum(p.stat().st_size for p in files if p.is_file() and not p.is_symlink()),
              "largest": {"path": largest[1], "bytes": largest[0]}, "a5_published": len(expected), "problems": problems}
    print(json.dumps(report, indent=2))
    return 0 if not problems else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate")
    gen.add_argument("--check", action="store_true")
    sub.add_parser("sync-assets")
    dist = sub.add_parser("check-dist")
    dist.add_argument("dist", nargs="?", type=Path, default=ROOT / "doc" / "dist")
    args = parser.parse_args()
    if args.command == "generate":
        return cmd_generate(args.check)
    if args.command == "sync-assets":
        return cmd_sync_assets()
    return cmd_check_dist(args.dist.resolve())


if __name__ == "__main__":
    sys.exit(main())
